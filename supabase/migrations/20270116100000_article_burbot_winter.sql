## Как ловить

1. **Донная удочка:** наживку кладите на дно и ждите. Поклёвка налима — несколько слабых подёргиваний, затем сторожок плавно уходит вниз. Подсекайте, когда сторожок пошёл.
2. **Стукалка:** опустите на дно и постукивайте ею по грунту — шум и муть подманивают налима. Время от времени приподнимайте на 10–20 см и снова опускайте.
3. Налим упирается тяжело, но вяло. В лунку заводите его головой вперёд; для крупного налима нужна лунка 130–150 мм.

