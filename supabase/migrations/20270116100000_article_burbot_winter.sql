## Where to look

- **Rivers:** holes below riffles, channel edges with stony or sandy bottom, mouths of tributaries.
- **Reservoirs and lakes:** edges and drop-offs along the old river bed, stony ridges, depths of 4–10 m.
- Burbot stay at the bottom and come to places where small fish feed. If ruffe bite in a hole, burbot are often nearby.

## What to take

- **Bottom rod** — a short rod with a reel and a bite indicator; line 0.25–0.3 mm; a long-shank hook No. 6–8 (burbot swallow deep).
- **Tapping rig** — a heavy vertical spoon or a sinker with a hook baited with a piece of fish or a bunch of worms.
- **Bait:** small fish, live or dead, pieces of fish, a bunch of dung worms. Burbot find food by smell, so fresh bait matters more than a lure.
- **Tip-ups** catch burbot too: lower the live bait to the bottom. The Fishing Rules do not limit how many tip-ups you set.
- **Disgorger** or long forceps to remove a deeply swallowed hook.

## How to fish

1. **Bottom rod:** lay the bait on the bottom and wait. A burbot bite is a few weak twitches, then the indicator slowly goes down. Strike when it goes.
2. **Tapping rig:** lower it to the bottom and tap the ground with it — the noise and the silt draw burbot in. Now and then lift it 10–20 cm and drop it again.
3. A burbot pulls heavily but slowly. Guide it into the hole head first; a big burbot needs a hole of 130–150 mm.

## At night on the ice

- Go in pairs, take a headlamp and a spare light, keep your phone warm and charged.
- Mark the way to your holes and back while it is light, and mark the holes with sticks: in the dark they are easy to lose and easy to step into.
- At night, stay off river ice over the current and near open water.
- Warm layers, dry spare socks and mittens, a hot drink.

## What the rules say

- **No fishing with amateur gear at night in the Zhaiyk-Caspian basin:** on the waters of West Kazakhstan and Atyrau regions, the Kigash and the North Caspian from 22:00 to 06:00 local time, all year (Order No. 78). Night fishing for burbot on the Zhaiyk is banned.
- **Minimum size of burbot** is 45 cm on the waters of Kostanay and Aktobe regions, including the Verkhnetobolsk and Karatomar reservoirs (appendix 1 of the Fishing Rules). Release burbot below the minimum.
- **Up to 5 kg of fish per trip** is free and needs no permit; more needs a permit from the local executive body (Fishing Rules, para. 20).
