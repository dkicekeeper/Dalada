   $md$The burbot is the only freshwater fish of the cod order. It likes cold water: in summer it is sluggish in the warm water, and in winter, when other fish slow down, it comes out to feed. Burbot spawn in winter too, under the ice. They bite mostly at dusk and at night, right at the bottom.

In Dalada, burbot are listed for the Ertis — in Oskemen, Semey and Pavlodar — for Ust-Kamenogorsk Reservoir and Zaysan, for the Zhaiyk in Oral and Atyrau, and for the Verkhnetobolsk, Karatomar and Sherubainura reservoirs.

