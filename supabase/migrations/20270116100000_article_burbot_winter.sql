- **Banned methods** — everywhere: snagging, spearing, electric current, self-catching gear and trotlines.

## Releasing a burbot

- A burbot is slippery: hold it from below with a wet glove and do not squeeze hard.
- Do not tear out a deeply swallowed hook: cut the leader close to the mouth instead.
- Release it right away: in frost the gills freeze fast.

