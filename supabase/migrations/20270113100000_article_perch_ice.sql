   $md$Perch are the most common winter catch: they bite on first ice, in midwinter and on last ice, in frost and in a thaw, and live in many waters across the country. Perch move in schools, so the main thing is to find the school: where one bites, there are others nearby.

In Dalada, perch are listed for the Bukhtarma, Kapshagay, Vyacheslavskoye and Seletinskoye reservoirs, Zaysan and Alakol, lakes Shchuchye and Bolshoye Chebachye — and many other waters.

Ice first: what ice holds you and what to do if you fall through — see “Ice safety”.

## Where to look

- **First ice:** perch hold in shallows of 1–3 m — by weed and reeds, at the exits from bays. The bite is best in the first weeks after freeze-up.
- **Midwinter:** schools move deeper, to drop-offs and edges of 4–8 m, towards holes. They bite more cautiously, mostly in the morning and before sunset.
- **Last ice:** perch come back to the shallows, to stream mouths and open patches.
- Drill 5–8 holes at once in a line across the drop-off, 10–15 m apart, and fish each for 3–5 minutes. No bites — move on: perch rarely stay in one place all day.

## What to take

- **Rod** 40–60 cm with a spring bite indicator, which shows a bite before your hand feels it.
- **Line** 0.10–0.14 mm for a jig and 0.15–0.18 mm for a balance lure or spoon.
- **Jigs** 2–4 mm — tungsten ones sink faster than lead and hold depth better. Bait — bloodworm.
- **Balance lure** 3–5 cm and **vertical spoon** 3–5 cm — to find active perch.
- **Ice auger** 100–110 mm: a small hole is enough for perch.

## How to work the lure

1. **Jig.** Drop it to the bottom, lift 5–10 cm and raise it 20–40 cm with small quick shakes of the indicator. A bite stops the indicator or lifts it: strike short.
2. **Balance lure.** A sharp lift of 15–30 cm, the lure darts to the side and swings back in a circle; pause for 3–5 seconds. Perch take on the pause.
3. **Spoon.** Lift 10–20 cm, let it fall freely, pause. Now and then tap the bottom with the spoon: a puff of silt draws the school in.
4. If perch come up but do not take, switch to a smaller jig and thinner line.

## What the rules say

- **There is no minimum size for perch:** appendix 1 of the Fishing Rules, which lists minimum sizes, does not include perch. Still, let the small ones go — they grow into big perch.
- **Up to 5 kg of fish per trip** is free and needs no permit; more needs a permit from the local executive body (Fishing Rules, para. 20).
- **Wintering pits.** Fishing in wintering pits in winter is banned (Order No. 78). On the Zhaiyk and Kigash the pits are listed by name — the list is in Dalada, in the rules of these rivers.
- **The Bukhtarma in autumn.** From 10 November to 10 December all fishing is banned on Bukhtarma Reservoir from a line 3 km above the Kaiyndy mouth down to the dam — even if the ice has already formed.
- **Banned methods** — everywhere: snagging (hooking a fish by the body), spearing, electric current.
- **On assigned waters** — those with a user: a fish farm, a paid pond — you need a voucher (para. 21).

