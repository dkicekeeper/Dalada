## Тербелмелі блеснолар (колебалкалар)

Тартқанда «бұлаңдайтын» иілген пластина. Алысқа ұшады — балық жағадан алыста шабуылдағанда ыңғайлы.

- Ақмарқа, шортан, көксерке. Ақмарқаға — жіңішке әрі ауырлары, оларды ол шабақ қуып жүрген «қазанға» лақтырады.

## Воблерлер

Қалақшасы бар пластик балықшалар: воблердің қандай тереңдікке түсетінін қалақша анықтайды.

- Қалқымалы әрі таяз жүретіндері — қамыс жанындағы шортан мен алабұғаға; терең жүретіндері — ернеулердегі көксерке мен жайынға.
- Үзілісі бар жұлқымалы тартуды байқаңыз: жыртқыш көбіне үзіліс кезінде шабуылдайды.

## Силикон жемдер және джиг

Джиг-бастағы жұмсақ твистерлер мен виброқұйрықтар. Бұл — көксеркені аулаудың басты тәсілі.

1. Лақтырып, жем түбіне жатқанша күтіңіз: жіп салбырап қалады.
2. Катушканы екі-үш айналдырыңыз — жем түптен секіріп көтеріледі.
3. Қайтадан түбіне тигенше үзіліс жасаңыз. Қаптыру көбіне жем түсіп бара жатқанда болады.

## Ең аз жиынтық

- Әр түрлі көлемдегі 2–3 вертушка.
- 2 колебалка — жеңіл және ауыр.
- 2 воблер — таяз және терең жүретін.
- 7–10 см виброқұйрықтар және 10–20 г джиг-бастар.
- Металл жетекшілер — шортан бар жерде: ол жіпті тістеп үзеді.

