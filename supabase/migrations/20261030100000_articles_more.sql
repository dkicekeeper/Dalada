## Spinners

A blade spins around the shaft and creates a vibration fish feel even in murky water.

- Good for perch, pike and asp in shallow water and in current.
- Retrieve steadily, so the blade never stops spinning.

## Spoons

A curved metal plate that wobbles on the retrieve. They cast far — handy when fish are feeding well away from the bank.

- Asp, pike, zander. For asp use narrow, heavy spoons and cast them at the "boil" where it is chasing fry.

## Wobblers (crankbaits)

Plastic fish with a lip: the lip decides how deep the wobbler dives.

- Floating, shallow-running ones for pike and perch by the reeds; deep divers for zander and catfish on drop-offs.
- Try a jerky retrieve with pauses: predators often strike on the pause.

## Soft plastics and jigging

Soft twisters and paddle tails on a jig head. This is the main way to catch zander.

1. Cast and wait for the lure to settle on the bottom: the line goes slack.
2. Two or three turns of the reel — the lure hops off the bottom.
3. Pause until it touches the bottom again. Most bites come as it falls.

## A minimal kit

- 2–3 spinners of different sizes.
- 2 spoons — a light one and a heavy one.
- 2 wobblers — a shallow and a deep one.
- Paddle tails of 7–10 cm and 10–20 g jig heads.
- Wire leaders where there are pike: they bite through line.

