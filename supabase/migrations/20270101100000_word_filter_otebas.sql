-- Фильтр грубых слов ложно задевал казахское название озера «Отебас» (Кызылординская область):
-- шаблон корня «еб» с приставкой «от» находил в нём «отеба». Теперь слово, которое начинается с
-- «отебас», шаблон пропускает (отрицательная проверка вперёд); остальные формы корня — «отъебись»,
-- «отебал», «заебал» — находятся по-прежнему.

update private.banned_patterns
   set pattern = '\m(?!отебас)(на|за|вы|по|у|от|отъ|до|раз|разъ|рас|об|объ|под|подъ|про|съ|вз|въ|при|пере)?[её]б(а|у|л|н|ы|и|е|ё|о|т|ш|щ)',
       note = 'корень «еб»; не «Отебас» (озеро)'
 where note = 'корень «еб»';
