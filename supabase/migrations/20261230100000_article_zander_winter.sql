## Где искать

- **Твёрдое дно у глубины.** Судак держится там, где песок, ракушка или галька переходят в свал: на бровках русла, у затопленных русел рек в водохранилищах, на выходах из ям.
- **Коряжник и бетон.** Затопленные деревья, старые опоры и каменные гряды — его укрытия.
- **Глубина** обычно 4–12 м; по первому льду судак бывает и мельче, в глухозимье — глубже.
- Сверлите цепочку лунок поперёк свала и облавливайте каждую по 5–10 минут.

## Чем ловить

- **Удочка** — жёсткая, 50–70 см, с чувствительным кончиком: поклёвка судака бывает осторожной.
- **Леска** 0,2–0,25 мм или тонкий шнур с поводком из флюорокарбона: судак осторожен и не любит толстой лески.
- **Вертикальная блесна** 5–9 см — узкая, «судачья».
- **Балансир** 5–7 см и **раттлин** (тонущий воблер без лопасти) — когда судак активен.
- **Жерлица** с небольшим живцом и тонким поводком — на ночь и утро.

## Как играть приманкой

1. Опустите приманку до дна и поднимите на 5–10 см.
2. Плавный подброс на 15–30 см и свободное падение.
3. Пауза 5–10 секунд. Судак чаще всего берёт на паузе или на падении.
4. Иногда простучите приманкой по дну: облачко мути привлекает судака.

Подсекайте сразу и уверенно: пасть у судака твёрдая и костистая. Для судака удобнее лунки 130–150 мм.

## Что запрещено зимой

- **Зимовальные ямы.** Ловить в зимовальных ямах зимой запрещено (приказ № 78). На Жайыке и Кигаше ямы перечислены поимённо — Буровиков, Тендыкская, Большая и Малая Дамбинская и другие; список есть в Dalada, в правилах этих рек.
- **Бухтарма осенью.** С 10 ноября по 10 декабря любая рыбалка запрещена на Бухтарминском водохранилище от линии в 3 км выше устья Каиынды до Бухтарминской ГЭС — даже если лёд уже встал.
- **Запрещённые способы.** Багрить (цеплять рыбу крючком за тело) и ловить острогой нельзя нигде.
- **Промысловая мера судака** разная: 32 см в Павлодарской области, 35 см в Нура-Сарысуском бассейне, 37 см на Балхаше, Алакольских озёрах, в Актюбинской и Атырауской областях, 38 см на Капшагае, Бухтарме, Шульбе и Сырдарье, 42 см в Шу-Таласском бассейне, 43 см в Западно-Казахстанской области, 45 см в Костанайской. Мера для вашего места — в Dalada.

## Как отпустить судака

- Не держите судака за жабры и глаза; на спинном плавнике у него острые колючки — берите рыбу снизу, под брюхо.
- Крючок доставайте экстрактором и отпускайте сразу: на морозе жабры быстро обмерзают.
- Судак, поднятый с большой глубины, может не уйти вниз сам. Подержите его в лунке головой вниз, пока не начнёт двигать жабрами и не уйдёт.

