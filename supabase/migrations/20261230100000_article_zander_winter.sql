## Where to look

- **Hard bottom next to depth.** Zander hold where sand, shells or gravel meet a drop-off: on channel edges, over drowned river beds in reservoirs, at the exits from holes.
- **Snags and concrete.** Sunken trees, old piers and rocky ridges are their cover.
- **Depth** is usually 4–12 m; on first ice zander can be shallower, in midwinter deeper.
- Drill a line of holes across the drop-off and fish each for 5–10 minutes.

## What to use

- **Rod** — stiff, 50–70 cm, with a sensitive tip: a zander bite can be cautious.
- **Line** 0.2–0.25 mm, or thin braid with a fluorocarbon leader: zander are wary of thick line.
- **Vertical spoon** 5–9 cm — a narrow “zander” spoon.
- **Balance lure** 5–7 cm and **lipless crankbait** (rattle bait) — when zander are active.
- **Tip-up** with a small live bait and a thin leader — for the night and morning.

## How to work the lure

1. Drop the lure to the bottom and lift it 5–10 cm.
2. Lift it smoothly 15–30 cm and let it fall freely.
3. Pause for 5–10 seconds. Zander usually take on the pause or on the fall.
4. Now and then tap the bottom with the lure: a puff of silt draws zander in.

Strike at once and firmly: a zander’s mouth is hard and bony. Holes of 130–150 mm suit zander best.

## What is banned in winter

- **Wintering pits.** Fishing in wintering pits in winter is banned (Order No. 78). On the Zhaiyk and Kigash the pits are listed by name — Burovikov, Tendyk, Big and Small Dambinskaya and others; the list is in Dalada, in the rules of these rivers.
- **The Bukhtarma in autumn.** From 10 November to 10 December all fishing is banned on Bukhtarma Reservoir from a line 3 km above the Kaiyndy mouth down to the Bukhtarma dam — even if the ice has already formed.
- **Banned methods.** Snagging (hooking a fish by the body) and spearing are banned everywhere.
- **Minimum size of zander** varies: 32 cm in Pavlodar Region, 35 cm in the Nura-Sarysu basin, 37 cm on Balkhash, the Alakol lakes and in Aktobe and Atyrau regions, 38 cm on Kapshagay, the Bukhtarma, Shulba and the Syr Darya, 42 cm in the Shu-Talas basin, 43 cm in West Kazakhstan Region, 45 cm in Kostanay Region. The minimum for your spot is in Dalada.

## Releasing a zander

- Do not hold a zander by the gills or eyes; its dorsal fin has sharp spines — hold the fish from below, under the belly.
- Remove the hook with a disgorger and let it go right away: in frost the gills freeze fast.
- A zander brought up from great depth may not be able to swim down on its own. Hold it head down in the hole until it starts working its gills and swims off.

