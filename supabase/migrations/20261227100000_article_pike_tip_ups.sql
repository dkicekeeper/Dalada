## Как устроена жерлица

- **Основание** закрывает лунку от снега и света, или **стойка** держит снасть над лункой.
- **Катушка** с основной леской 0,3–0,4 мм, 10–15 м.
- **Флажок** на гибкой пружине: его цепляют за катушку, и он распрямляется, когда катушка начинает вращаться.
- **Грузило** 5–10 г над поводком держит живца на нужной глубине.
- **Поводок** 20–30 см — металлический или из толстого флюорокарбона: обычную леску щука перекусывает.
- **Крючок** — двойник, тройник или одинарный, по размеру живца.

## Живец

- Лучший живец — рыбка из того же водоёма длиной 8–15 см: окунь, плотва, карась. Ловите её мормышкой в первый час и держите в ведре с водой из лунки, воду время от времени меняйте.
- Крючок ставят под спинной плавник или за губу — так живец дольше остаётся подвижным.
- Промысловая мера касается и живца. В Актюбинской области, например, плотву меньше 19 см и карася меньше 21 см забирать нельзя. У окуня меры в Правилах рыболовства нет.

## Где ставить

- **Первый лёд** (обычно декабрь): щука стоит на мелководье 1–3 м — у края камыша и травы, на выходах из заливов.
- **Глухозимье** (январь–февраль): уходит глубже, на свалы и бровки 3–6 м, ближе к ямам, где держится мелкая рыба.
- **Последний лёд** (март): снова подходит к берегам и устьям ручьёв.
- На мелководье живца держат посередине между дном и льдом, на глубине — в 20–40 см от дна.
- Ставьте жерлицы цепочкой поперёк перепада глубин, в 10–20 м одна от другой, так, чтобы видеть все флажки. Если за час-два не было ни одной поклёвки — переставьте цепочку.

## Сработал флажок

1. Подходите спокойно, не бегом: на льду легко поскользнуться, а шум у лунки пугает щуку.
2. Если катушка крутится — щука уносит живца. Подождите, пока она остановится: в это время щука разворачивает рыбку головой к себе, чтобы заглотить.
3. Когда катушка снова начнёт вращаться, подсекайте резким движением руки вверх и выбирайте леску руками, без рывков.
4. Крупную щуку заводите в лунку головой вперёд. Для щуки удобнее лунки 130–150 мм.

Если катушка сделала пару оборотов и встала, это может быть ветер или мелкая рыба. Подождите 5–10 минут и проверьте живца.

