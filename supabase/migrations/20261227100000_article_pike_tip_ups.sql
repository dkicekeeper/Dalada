## Как отпустить щуку

- Держите щуку мокрой перчаткой за спину позади головы, не трогайте жабры и глаза.
- Крючок доставайте длинным экстрактором или зажимом: пасть щуки усеяна зубами.
- Отпускайте сразу: на морозе жабры и глаза рыбы быстро обмерзают.

Подробнее — в статье «Как отпустить рыбу, чтобы она выжила».

