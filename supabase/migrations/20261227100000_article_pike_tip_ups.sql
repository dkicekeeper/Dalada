## How a tip-up works

- A **base** covers the hole from snow and light, or a **stand** holds the rig over the hole.
- A **spool** with 0.3–0.4 mm main line, 10–15 m.
- A **flag** on a flexible spring: it is hooked onto the spool and straightens when the spool starts to turn.
- A 5–10 g **sinker** above the leader keeps the bait at the right depth.
- A 20–30 cm **leader** — wire or thick fluorocarbon: pike bite through ordinary line.
- A **hook** — double, treble or single, sized to the bait.

## Live bait

- The best bait is a fish from the same water, 8–15 cm long: perch, roach, crucian carp. Catch it with a jig in the first hour and keep it in a bucket of water from the hole, changing the water now and then.
- Hook it under the dorsal fin or through the lip — that keeps the bait lively for longer.
- Minimum sizes apply to bait fish too. In Aktobe Region, for example, you may not keep roach under 19 cm or crucian carp under 21 cm. The Fishing Rules set no minimum size for perch.

## Where to set them

- **First ice** (usually December): pike hold in 1–3 m of water — at the edge of reeds and weeds, at the mouths of bays.
- **Midwinter** (January–February): they move deeper, to drop-offs and ledges of 3–6 m near the holes where small fish gather.
- **Last ice** (March): they come back towards the banks and stream mouths.
- In shallow water keep the bait halfway between the bottom and the ice; in deep water, 20–40 cm off the bottom.
- Set tip-ups in a line across a depth change, 10–20 m apart, so you can see every flag. If there is no bite in an hour or two, move the line.

## Flag up

1. Walk, don’t run: it is easy to slip on the ice, and noise by the hole spooks the pike.
2. If the spool is turning, the pike is carrying the bait away. Wait until it stops: the pike is turning the fish head first to swallow it.
3. When the spool starts turning again, strike with a sharp upward move of the hand and pull the line in by hand, without jerks.
4. Guide a big pike into the hole head first. Holes of 130–150 mm suit pike best.

If the spool turns once or twice and stops, it may be the wind or a small fish. Wait 5–10 minutes and check the bait.

## What the rules say

- **Tip-ups are allowed** for amateur fishing: the Fishing Rules (para. 19) and the list of permitted fishing gear (para. 26). Neither limits how many you may set.
- **Up to 5 kg of fish per trip** is free and needs no permit; more needs a permit from the local executive body (Fishing Rules, para. 20).
- **On assigned waters** — those with a user such as a fish farm or a paid pond — you need a voucher from the user (para. 21). Ask the user about the conditions.
- **Minimum size of pike** depends on the basin: 45 cm in Kostanay Region, 42 cm in Akmola and North Kazakhstan regions, 40 cm in Aktobe Region, 32 cm on the Bukhtarma and Zaysan, 30 cm on the Zhaiyk, 25 cm in the Nura-Sarysu basin. Release pike below the minimum.
- **Spring brings spawning bans.** In some regions the ban starts while the ice still holds: from 10 April on the waters of the Esil basin.
- Carry an identity document (para. 22).

## Releasing a pike

- Hold the pike with a wet glove across the back behind the head; do not touch the gills or the eyes.
- Remove the hook with long forceps or a disgorger: a pike’s mouth is full of teeth.
- Let it go right away: in frost a fish’s gills and eyes freeze fast.

More in “How to release a fish so it survives”.

## Leaving the ice

- Take every tip-up and all bits of line with you: lost tackle kills fish and birds.
- Mark wide holes with a stick or a heap of snow: it is easy to step into them.

