## Где искать

- **Плотва:** у края травы и камыша, на 2–4 м; на первом и последнем льду — ближе к берегу. Клюёт днём.
- **Лещ:** на глубине 5–10 м — бровки, ямы, старое русло, илистое дно рядом с твёрдым. Клюёт утром, вечером и ночью.
