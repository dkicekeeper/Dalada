## Что взять

- **Удочка** с чувствительным кивком: поклёвка плотвы и леща слабая, её видно только по кивку.
- **Леска** 0,08–0,12 мм для плотвы и 0,12–0,14 мм для леща.
- **Мормышки** 2–4 мм — вольфрамовые, тёмные или латунного цвета; насадка — 1–3 мотыля.
