## Where to look

- **Roach:** by the edge of weed and reeds, at 2–4 m; on first and last ice closer to the shore. They bite in the daytime.
- **Bream:** at 5–10 m — edges, holes, the old river bed, silt next to a hard bottom. They bite in the morning, in the evening and at night.
- Drill several holes at different depths and stay where you had even one bite: roach and bream come to groundbait slowly.

## What to take

- **Rod** with a sensitive spring indicator: roach and bream bites are weak and show only on the indicator.
- **Line** 0.08–0.12 mm for roach and 0.12–0.14 mm for bream.
- **Jigs** 2–4 mm — tungsten, dark or brass-coloured; bait — 1–3 bloodworms.
- **Ice feeder** — lowered to the bottom and opened with a jerk, so the groundbait settles by the hole instead of scattering in the water.
- **Groundbait:** feeder bloodworm, breadcrumbs, soil from the same water. No strong smells: in winter roach and bream avoid them.

## How to fish

1. **Feed.** Lower the feeder with a pinch of bloodworm and mix into the hole and open it at the bottom. Top up a little once an hour — overfed fish stop taking.
2. **Roach.** Take the jig to the bottom, then raise it slowly 20–40 cm with small quick shakes of the indicator and pauses. A bite makes the indicator twitch or stop.
3. **Bream.** Keep the jig right at the bottom, lift 5–10 cm and lay it down again. Bream often lift the bait — the indicator straightens upward: that is the bite.
4. Guide a big bream into the hole head first, without jerks: its lips are soft. A 130 mm hole suits bream.

## What the rules say

- **Minimum size of bream** depends on the basin: 19 cm on Balkhash, the Ile below Kapshagay and in Aktobe Region, 20 cm in Kyzylorda and Kostanay regions, 22 cm on the Verkhnetobolsk and Karatomar reservoirs, 21 cm in the Shu-Talas basin, 24 cm in West Kazakhstan and Atyrau regions and the Caspian, 26 cm on Kapshagay.
- **Minimum size of roach** is 17 cm in Kyzylorda Region and the Small Aral, 19 cm in Aktobe Region and the Shu-Talas basin; Caspian roach — 17 cm on the Caspian and in West Kazakhstan Region, 18 cm in Atyrau Region. Release fish below the minimum.
- **Up to 5 kg of fish per trip** is free and needs no permit; more needs a permit from the local executive body (Fishing Rules, para. 20).
