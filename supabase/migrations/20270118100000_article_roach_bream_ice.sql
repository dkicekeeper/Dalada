- **Прикормка:** кормовой мотыль, панировочные сухари, грунт из того же водоёма. Без резких запахов: зимой белая рыба их не любит.

## Как ловить

1. **Прикормите.** Опустите в лунку кормушку с щепотью мотыля и смеси и откройте её у дна. Подкармливайте понемногу раз в час — перекормленная рыба не берёт.
