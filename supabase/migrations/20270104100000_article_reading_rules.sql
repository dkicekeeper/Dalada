   $md$Fishing bans in Kazakhstan are set by the Ministry of Agriculture. Dates and places are in the order on bans (currently Order No. 78 of 3 March 2026), while gear, catch limits and minimum sizes are in the Fishing Rules. The order gives dates “of the corresponding year”: they are the same every year until a new order comes out. New orders usually appear by spring, and Dalada checks its rules against the source.

## Kinds of rules

- **Spawning ban** — in spring and summer, while fish spawn. Each water has its own dates: on Kapshagay from 5 April to 20 May, on the waters of the Esil basin from 10 April to 20 May, in Kostanay Region from 20 April to 10 June.
- **“All fishing”** and **“with amateur gear”** are not the same. In the first case you may not fish at all. In the second, rods, spinning and other amateur gear are banned: on the Zhaiyk in West Kazakhstan Region from 10 April to 15 June, and at night, from 22:00 to 06:00, all year.
- **Rest zone** — a place where fishing is banned all year: for example, the Kara Ertis, the Arys and Keles rivers, the mouth of the Zhaiyk.
- **Species ban** — all year or for a season: sturgeon may not be caught anywhere, whitefish in the east from 10 November to 10 December, crayfish in spring.
- **Banned methods** — everywhere: spears, self-catching gear, trotlines, electric current, snagging.
- **Minimum size** — release fish shorter than the minimum. It differs by basin and sometimes by reservoir.

## How it looks in Dalada

1. Tap **“Bans”** on the map. Zones where a ban is on today are shown in red, zones where one starts within 30 days in the warning colour, and other zones with rules in grey.
2. Open a place and find **“Rules here”**: what applies now, what starts soon, the minimum sizes and a link to the whole zone.
3. A rule card shows its text, the clause of the order with a link to adilet.zan.kz and the date the rule was checked.
4. When you log a catch, the form warns you if the fish is below the minimum size.
5. If you have a saved or your own place in a ban zone and notifications are on, Dalada reminds you the day before a ban starts and tells you when it ends.

## Worth remembering

- **Map borders are approximate.** A “waters of the region” zone follows the region boundary, and a river is drawn as a strip along its channel. The rule text matters more than the line on the map: if a rule names a water, it applies to the whole water.
- **Dates are inclusive.** “From 10 April to 20 May” means you may not fish on 10 April and 20 May either.
- **Local time.** The night ban on the Zhaiyk follows local time.
- **Assigned waters.** If a water has a user (a fish farm, a paid pond), you need a voucher, and their conditions may be stricter.
- **In doubt — check the source.** Every rule card links to the order.

