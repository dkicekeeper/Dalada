## Какие бывают правила

- **Нерестовый запрет** — весной и летом, пока рыба мечет икру. У каждого водоёма свои сроки: на Капшагае с 5 апреля по 20 мая, на водоёмах Есильского бассейна — с 10 апреля по 20 мая, в Костанайской области — с 20 апреля по 10 июня.
